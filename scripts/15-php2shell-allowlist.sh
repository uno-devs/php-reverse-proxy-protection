#!/bin/sh
# Builds the multipart filter used by default.conf.template from $UPLOAD_PATHS
# (comma-separated exact URI paths that may receive multipart/* requests).
set -eu

out=/etc/nginx/conf.d/00-php2shell.conf
paths="${UPLOAD_PATHS:-}"

{
  echo '# generated by 15-php2shell-allowlist.sh'
  echo '# PHP2Shell (CVE-2026-109618/109619): multipart parsing is the main trigger.'
  echo 'map $http_content_type $is_multipart {'
  echo '    default       0;'
  echo '    "~*multipart" 1;'
  echo '}'
  echo 'map "$is_multipart|$uri" $block_multipart {'
  echo '    default 0;'
  if [ -n "$paths" ]; then
    alt=""
    old_ifs=$IFS; IFS=,
    for p in $paths; do
      case "$p" in
        /*) ;;
        *) echo "UPLOAD_PATHS: '$p' must start with /" >&2; exit 1 ;;
      esac
      case "$p" in
        *[!A-Za-z0-9/_.-]*) echo "UPLOAD_PATHS: '$p' has disallowed characters" >&2; exit 1 ;;
      esac
      esc=$(printf '%s' "$p" | sed 's/\./\\./g')
      alt="${alt:+$alt|}$esc"
    done
    IFS=$old_ifs
    echo "    \"~^1\\|($alt)\$\" 0;"
  fi
  echo '    "~^1\|"  1;'
  echo '}'
} > "$out"

echo "php2shell: multipart blocked except on: ${paths:-<none>}"
